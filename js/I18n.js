/* ===================
   IDIOMA (ES / EN)
   Español por defecto
==================== */
let currentLang = 'es';
try {
    const savedLang = localStorage.getItem('lang');
    if (savedLang === 'es' || savedLang === 'en') currentLang = savedLang;
} catch (e) {}

function t(key){
    return (I18N[currentLang] && I18N[currentLang][key]) || I18N.es[key] || key;
}

function applyLang(lang){
    currentLang = lang;
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        el.textContent = t(el.dataset.i18n);
    });

    document.querySelectorAll('[data-i18n-attr]').forEach(el => {
        el.dataset.i18nAttr.split(';').forEach(pair => {
            const [attr, key] = pair.split(':');
            el.setAttribute(attr, t(key));
        });
    });

    document.title = t('meta.title');
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) metaDesc.setAttribute('content', t('meta.desc'));

    // El botón muestra el idioma al que se puede cambiar
    langBtn.textContent = lang === 'es' ? 'EN' : 'ES';
    langBtn.setAttribute('aria-label', t('lang.switch'));
    langBtn.setAttribute('title', t('lang.switch'));

    document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
}

const langBtn = document.getElementById('lang-toggle');
langBtn.addEventListener('click', () => {
    const next = currentLang === 'es' ? 'en' : 'es';
    applyLang(next);
    try { localStorage.setItem('lang', next); } catch (e) {}
});


// Aplicar el idioma inicial (español por defecto)
applyLang(currentLang);